def tr(value: str, language: str = "en") -> str:
    """Translate a known UI phrase; preserve source data and proper names."""
    return ML.get(value, value) if language == "ml" else value


def drivers(row, language: str = "en", top: int = 3) -> list[str]:
    """Explain signed model drivers without changing the numeric contribution."""
    from visat.report import DRIVER_WORDS

    values = {k.split("::", 1)[1]: v for k, v in row.items()
              if str(k).startswith("drv::")}
    values.pop("Weather of the day", None)
    result = []
    for group, value in sorted(values.items(), key=lambda pair: -abs(pair[1]))[:top]:
        warm, cool = DRIVER_WORDS.get(group, (group, group))
        if language == "ml":
            result.append(f"{tr(warm if value > 0 else cool, language)} "
                          f"ചൂട് {('കൂടുന്നു' if value > 0 else 'കുറയുന്നു')} "
                          f"({abs(value):.1f} °C)")
        else:
            result.append(f"{warm if value > 0 else cool} "
                          f"{'adds' if value > 0 else 'removes'} {abs(value):.1f} °C")
    return result
